"""Write the fixed 50-document corpus for the Gate F ingestion scenario (protocol section 5, S7).

Run once from backend/:   uv run python ..\\scripts\\make_corpus.py
Writes experiments/corpus/gate-f-50/ and MANIFEST.json (SHA-256 of every file). The measurement harness refuses to run
if any file no longer matches the manifest, so every run ingests exactly the same bytes. Refuses to overwrite an
existing corpus (delete the folder first if it really must be rebuilt; results from different corpora do not compare).

Content: the Python standard-library documentation (pydoc), as in the Gate D live test, cut to about 6,000 characters
per document (about three chunks), in the five supported formats; CSV files are generated tables. Reuses the Gate D
generators in backend/tests/kb_helpers.py (python-docx for DOCX, a minimal PDF writer).
"""

from __future__ import annotations

import importlib
import json
import pydoc
import random
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "backend"))

from tests.kb_helpers import write_csv, write_docx, write_pdf  # noqa: E402
from xodus.experiments.harness import sha256_file  # noqa: E402

OUT = REPO / "experiments" / "corpus" / "gate-f-50"
CHARS = 6000
TXT = ["json", "re", "csv", "sqlite3", "threading", "datetime", "argparse", "hashlib", "random", "zipfile", "shutil",
       "tempfile", "collections", "itertools", "functools", "logging", "string", "base64", "uuid", "fractions", "decimal",
       "operator", "copy", "pprint", "enum", "dataclasses", "contextlib", "abc", "secrets", "gzip"]
MD = ["subprocess", "pathlib", "glob", "fnmatch", "difflib", "calendar", "time", "struct"]
PDF = ["statistics", "textwrap", "heapq", "bisect"]
DOCX = ["array", "queue", "sched", "weakref"]
CSV = ["sales", "sensors", "inventory", "timetable"]


def module_text(name: str) -> str:
    text = pydoc.plain(pydoc.render_doc(importlib.import_module(name), renderer=pydoc.plaintext))
    return re.sub(r"[^\x09\x0a\x20-\x7e]", " ", text)[:CHARS]


def csv_table(kind: str, rng: random.Random) -> tuple[list[str], list[list[str]]]:
    if kind == "sales":
        return ["month", "region", "units", "revenue_eur"], [
            [f"2025-{m:02d}", r, str(rng.randint(80, 900)), f"{rng.uniform(1e3, 9e4):.2f}"]
            for m in range(1, 13) for r in ("north", "south", "east", "west")]
    if kind == "sensors":
        return ["timestamp", "sensor", "temperature_c", "humidity_pct"], [
            [f"2025-06-01T{h:02d}:{mi:02d}", f"s{s}", f"{rng.uniform(15, 32):.1f}", f"{rng.uniform(30, 80):.0f}"]
            for h in range(24) for mi in (0, 30) for s in (1, 2)]
    if kind == "inventory":
        items = ["bolt", "nut", "washer", "screw", "bracket", "hinge", "spring", "gear", "pulley", "bearing"]
        return ["sku", "item", "warehouse", "quantity", "reorder_level"], [
            [f"SKU-{i:04d}", rng.choice(items), rng.choice(["A", "B", "C"]), str(rng.randint(0, 500)), str(rng.randint(20, 80))]
            for i in range(120)]
    return ["route", "stop", "departure", "platform"], [
        [f"R{r}", f"Stop {s}", f"{6 + (r * 7 + s * 3) % 16:02d}:{(s * 11) % 60:02d}", str(1 + (r + s) % 6)]
        for r in range(1, 9) for s in range(1, 13)]


def main() -> int:
    if OUT.exists() and any(OUT.iterdir()):
        print(f"{OUT} already exists; refusing to overwrite the fixed corpus.")
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    rng = random.Random(20261029)
    for name in TXT:
        (OUT / f"{name}.txt").write_text(module_text(name), encoding="utf-8")
    for name in MD:
        (OUT / f"{name}.md").write_text(f"# {name} module\n\n" + module_text(name), encoding="utf-8")
    for name in PDF:
        text = module_text(name)
        write_pdf(OUT / f"{name}.pdf", [re.sub(r"\s*\n\s*", "\n", text[i:i + 2000]) for i in range(0, len(text), 2000)])
    for name in DOCX:
        paras = [" ".join(p.split()) for p in module_text(name).split("\n\n") if p.strip()]
        write_docx(OUT / f"{name}.docx", [("h1", f"{name} module")] + [("p", p) for p in paras])
    for name in CSV:
        header, rows = csv_table(name, rng)
        write_csv(OUT / f"{name}.csv", header, rows)
    files = sorted(p.name for p in OUT.iterdir() if p.name != "MANIFEST.json")
    assert len(files) == 50, len(files)
    manifest = {"description": "Fixed Gate F ingestion corpus (protocol S7). Generated by scripts/make_corpus.py with "
                               f"Python {sys.version.split()[0]}; do not edit.",
                "files": {name: sha256_file(OUT / name) for name in files},
                "bytes": sum((OUT / name).stat().st_size for name in files)}
    (OUT / "MANIFEST.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    print(f"{len(files)} files, {manifest['bytes']:,} bytes -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
